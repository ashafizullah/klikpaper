// Writes src-tauri/src/pdf/std14.rs: glyph widths of the standard 14 fonts and
// their encodings, from the Adobe Core14 AFM metrics that pdf-lib ships. The
// redaction code needs them for PDFs that use these fonts without a width
// table (common in files made by PHP libraries). Run with `bun scripts/std14.mjs`.
import { Encodings, Font } from "../node_modules/@cantoo/pdf-lib/dist/standard-fonts/index.mjs";
import { writeFileSync } from "node:fs";

const FONTS = ["Helvetica", "Helvetica-Bold", "Times-Roman", "Times-Bold", "Times-Italic", "Times-BoldItalic", "Symbol", "ZapfDingbats"];

// StandardEncoding (PDF 32000-1, Annex D): the built-in encoding of the Latin fonts.
const STANDARD = {
  39: "quoteright", 96: "quoteleft", 161: "exclamdown", 162: "cent", 163: "sterling", 164: "fraction", 165: "yen", 166: "florin",
  167: "section", 168: "currency", 169: "quotesingle", 170: "quotedblleft", 171: "guillemotleft", 172: "guilsinglleft",
  173: "guilsinglright", 174: "fi", 175: "fl", 177: "endash", 178: "dagger", 179: "daggerdbl", 180: "periodcentered",
  182: "paragraph", 183: "bullet", 184: "quotesinglbase", 185: "quotedblbase", 186: "quotedblright", 187: "guillemotright",
  188: "ellipsis", 189: "perthousand", 191: "questiondown", 193: "grave", 194: "acute", 195: "circumflex", 196: "tilde",
  197: "macron", 198: "breve", 199: "dotaccent", 200: "dieresis", 202: "ring", 203: "cedilla", 205: "hungarumlaut",
  206: "ogonek", 207: "caron", 208: "emdash", 225: "AE", 227: "ordfeminine", 232: "Lslash", 233: "Oslash", 234: "OE",
  235: "ordmasculine", 241: "ae", 245: "dotlessi", 248: "lslash", 249: "oslash", 250: "oe", 251: "germandbls",
};

function table(encoding) {
  const out = Array(256).fill("");
  for (const [code, name] of Object.values(encoding.unicodeMappings)) if (code < 256 && !out[code]) out[code] = name;
  return out;
}

const winAnsi = table(Encodings.WinAnsi);
const standard = Array(256).fill("");
// Printable ASCII is the same as WinAnsi but for the two quotes.
for (let c = 32; c < 127; c++) standard[c] = winAnsi[c];
for (const [code, name] of Object.entries(STANDARD)) standard[Number(code)] = name;

const staticName = (f) => f.toUpperCase().replace(/-/g, "_");
const list = (names) => `[\n${names.map((n) => `    "${n}",`).join("\n")}\n]`;
let rs = `//! Glyph widths (in 1/1000 em) and built-in encodings of the standard 14
//! fonts, for PDFs that use them without a width table. Generated by
//! scripts/std14.mjs from the Adobe Core14 AFM metrics shipped with pdf-lib;
//! do not edit.
//!
//! ${Font.load("Helvetica").Notice.split(/(?<=\.)\s*/).join("\n//! ").trim()}
//! The Core14 AFM files may be used, copied and distributed for any purpose
//! and without charge, with or without modification, provided that all
//! copyright notices are retained.

pub static WIN_ANSI: [&str; 256] = ${list(winAnsi)};

pub static STANDARD: [&str; 256] = ${list(standard)};

pub static SYMBOL_ENCODING: [&str; 256] = ${list(table(Encodings.Symbol))};

pub static ZAPF_DINGBATS_ENCODING: [&str; 256] = ${list(table(Encodings.ZapfDingbats))};
`;
for (const name of FONTS) {
  const metrics = [...Font.load(name).CharMetrics].sort((a, b) => (a.N < b.N ? -1 : a.N > b.N ? 1 : 0));
  rs += `\n/// ${name}, sorted by glyph name.\npub static ${staticName(name)}: &[(&str, u16)] = &[\n${metrics.map((m) => `    ("${m.N}", ${m.WX}),`).join("\n")}\n];\n`;
}
writeFileSync(new URL("../src-tauri/src/pdf/std14.rs", import.meta.url), rs);
